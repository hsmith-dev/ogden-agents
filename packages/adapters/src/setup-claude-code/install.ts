/**
 * Installing the Claude Agent ACP adapter (story 9.3) into Ogden Agents' own
 * data folder, only when the user clicks Install (AD-21: no terminal). The
 * installer itself is the shared `pinned-npm/install.ts` (epic 12 entry 4);
 * what follows is what is Claude Code's own, and how it works, unchanged:
 *
 * - Everything goes under `<dataDir>/agents/claude-code/`: the pinned
 *   `package.json` and `package-lock.json` (every package with its
 *   `integrity`, `pins/`, bumped by `scripts/agent-pins.mjs --update`) are
 *   written into a `.install-*` temp folder, `npm ci` runs there with npm's
 *   cache inside it, and the result is renamed into `adapter-<version>` (or
 *   `adapter-<version>-bundled`, with the Agent SDK's own `claude`), so a
 *   half-installed copy is never used (story 1.8's pattern).
 * - npm is `npm-cli.js` beside this Node, else the npm that launched Ogden
 *   Agents, else one on an absolute `PATH` entry ({@link findNpmCli}), run with `process.execPath` and an
 *   argument array: no shell, no `.cmd` (AGENTS.md), `--ignore-scripts` (the
 *   adapter needs no install script), and without the `npm_*` variables this
 *   server may have inherited. The user's own `.npmrc` (registry, proxy) still applies.
 * - A tarball that doesn't match the lock fails the whole install (npm's
 *   `EINTEGRITY`), and so does no output and no download for
 *   {@link NPM_IDLE_TIMEOUT_MS}. Any failure removes the temp folder.
 * - npm's output is read for progress (`--loglevel http`, one line per
 *   package fetched) and its error code; it is never logged or shown.
 *
 * Nothing is written outside the data folder: no global install, no `PATH`
 * or profile change, no admin rights.
 */
import { existsSync, readdirSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { CLAUDE_AGENT_ACP_PACKAGE, CLAUDE_CODE } from '../acp-claude-code/constants.js';
import {
  entryIn as sharedEntryIn,
  installPinnedNpm,
  NPM_IDLE_TIMEOUT_MS,
  npmEnv,
  packagesToFetch,
  pinnedVersionOf,
  removeStalePinnedInstalls,
  spawnNpm,
  type AdapterLock,
  type AdapterPins,
  type InstallPinnedNpmOptions,
  type NpmProcess,
  type NpmRunInput,
  type NpmRunner,
  type PinnedNpmSpec,
} from '../pinned-npm/install.js';
import pinnedLock from './pins/package-lock.json' with { type: 'json' };
import pinnedManifest from './pins/package.json' with { type: 'json' };

// Moved to `pinned-npm/` (epic 12 entry 4; npm-cli in story 6.9); still exported from here.
export { findNpmCli, pathOf, type FindNpmOptions } from '../pinned-npm/npm-cli.js';
export { NPM_IDLE_TIMEOUT_MS, npmEnv, packagesToFetch, spawnNpm, type AdapterLock, type AdapterPins, type NpmProcess, type NpmRunInput, type NpmRunner };

/** `<dataDir>/agents/claude-code`: the installed adapters and the temp folders an install works in. */
export const CLAUDE_CODE_DIR = join('agents', 'claude-code');

/** The pinned adapter (`pins/`, generated by `scripts/agent-pins.mjs`). */
export const ADAPTER_PINS: AdapterPins = { packageJson: pinnedManifest, lock: pinnedLock as AdapterLock };

/** `adapter-<version>[-bundled]`; a prerelease (`0.0.0-fixture`) may have no `-`, so `-bundled` is never taken for one. */
const INSTALLED_FOLDER = /^adapter-(\d+\.\d+\.\d+(?:-(?!bundled$)[0-9A-Za-z.]+)?)(-bundled)?$/;

/** Whether npm put a platform binary package of the Agent SDK in `project`. */
function hasBinary(project: string): boolean {
  try {
    return readdirSync(join(project, 'node_modules', '@anthropic-ai')).some((name) => name.startsWith('claude-agent-sdk-'));
  } catch {
    return false;
  }
}

/** Whether the lock has the Agent SDK's platform binaries (the real pins do; the test fixture doesn't). */
const locksBinaries = (lock: AdapterLock) =>
  Object.entries(lock.packages).some(([path, entry]) => entry.optional === true && path.startsWith('node_modules/@anthropic-ai/claude-agent-sdk-'));

/** How Claude Code's adapter is installed, for the shared installer. */
const SPEC: PinnedNpmSpec = {
  displayName: CLAUDE_CODE,
  dir: CLAUDE_CODE_DIR,
  packageName: CLAUDE_AGENT_ACP_PACKAGE,
  entry: ['dist', 'index.js'],
  folderName: (version, withBinary) => `adapter-${version}${withBinary ? '-bundled' : ''}`,
  isInstalledFolder: (name) => INSTALLED_FOLDER.test(name),
  binary: { locked: locksBinaries, present: hasBinary },
};

/** The adapter version `pins` installs. */
export function pinnedVersion(pins: AdapterPins = ADAPTER_PINS): string {
  return pinnedVersionOf(SPEC, pins);
}

/** The adapter's entry script inside an installed folder. */
const entryIn = (folder: string) => sharedEntryIn(SPEC, folder);

export interface InstalledAdapter {
  /** The entry script, `…/node_modules/@agentclientprotocol/claude-agent-acp/dist/index.js`. */
  path: string;
  version: string;
  /** Installed with the Agent SDK's own `claude`, so it needs no `claude` on this computer. */
  bundled: boolean;
}

/**
 * The adapter an install put in `<dataDir>/agents/claude-code/`, or
 * `undefined`. The pinned version comes first (bundled before not), then
 * the newest other version, so a release that bumps the pin keeps an
 * earlier install working.
 */
export function installedAdapter(dataDir: string, pins: AdapterPins = ADAPTER_PINS): InstalledAdapter | undefined {
  const dir = join(dataDir, CLAUDE_CODE_DIR);
  let names: string[];
  try {
    names = readdirSync(dir);
  } catch {
    return undefined;
  }
  const pinned = pinnedVersion(pins);
  const found = names
    .map((name) => ({ name, match: INSTALLED_FOLDER.exec(name) }))
    .filter((entry): entry is { name: string; match: RegExpExecArray } => entry.match !== null)
    .map(({ name, match }) => ({ path: entryIn(join(dir, name)), version: match[1]!, bundled: match[2] !== undefined }))
    .filter((adapter) => existsSync(adapter.path))
    .sort((a, b) => {
      if ((a.version === pinned) !== (b.version === pinned)) return a.version === pinned ? -1 : 1;
      if (a.version !== b.version) return b.version.localeCompare(a.version, 'en', { numeric: true });
      return Number(b.bundled) - Number(a.bundled);
    });
  return found[0];
}

/** The Claude Agent ACP adapter a chat or a sign-in runs, and what it needs. */
export interface LocatedAdapter {
  path: string;
  /** Its version, when it is the real adapter package. */
  version: string | null;
  /** Installed without the Agent SDK's own `claude`, so it runs only with the user's `claude`. */
  needsClaude: boolean;
}

/** The version in the `package.json` two folders up from `entry`, when that is the adapter package. */
function adapterVersionOf(entry: string): string | null {
  try {
    const manifest = JSON.parse(readFileSync(join(dirname(dirname(entry)), 'package.json'), 'utf8')) as { name?: unknown; version?: unknown };
    return manifest.name === CLAUDE_AGENT_ACP_PACKAGE && typeof manifest.version === 'string' ? manifest.version : null;
  } catch {
    return null;
  }
}

/**
 * Where the adapter is, read afresh at each call: `adapterPath` (a path, or
 * a function giving one: `$OGDEN_AGENTS_CLAUDE_ACP_PATH`, then a dev
 * install's `node_modules`) when it gives one, else what an install put in
 * `<dataDir>/agents/claude-code/`. `undefined` when there is none, or the
 * given path doesn't exist.
 */
export function locateClaudeAdapter(options: {
  adapterPath?: string | (() => string | undefined) | undefined;
  dataDir?: string | undefined;
  pins?: AdapterPins | undefined;
}): LocatedAdapter | undefined {
  const given = typeof options.adapterPath === 'function' ? options.adapterPath() : options.adapterPath;
  if (given !== undefined) return existsSync(given) ? { path: given, version: adapterVersionOf(given), needsClaude: false } : undefined;
  if (options.dataDir === undefined) return undefined;
  const installed = installedAdapter(options.dataDir, options.pins ?? ADAPTER_PINS);
  return installed === undefined ? undefined : { path: installed.path, version: installed.version, needsClaude: !installed.bundled };
}

export interface InstallAdapterOptions extends Omit<InstallPinnedNpmOptions, 'pins'> {
  /** Default {@link ADAPTER_PINS}; the tests pass a local fixture lock. */
  pins?: AdapterPins;
}

/** Removes the `.install-*` folders a crashed or killed install left in `<dataDir>/agents/claude-code/` (server start). */
export function removeStaleInstalls(dataDir: string, onError: (error: unknown) => void = () => {}): void {
  removeStalePinnedInstalls(SPEC, dataDir, onError);
}

/**
 * Installs the pinned adapter under `<dataDir>/agents/claude-code/`,
 * reporting progress. Resolves with what was installed, or rejects with an
 * {@link AgentSetupError} in plain words (its `details` carry the step and
 * npm's error code only) having left no temp folder and no half-installed copy.
 */
export async function installAdapter(options: InstallAdapterOptions): Promise<InstalledAdapter> {
  const { path, version } = await installPinnedNpm(SPEC, { ...options, pins: options.pins ?? ADAPTER_PINS });
  return { path, version, bundled: options.withBinary };
}
