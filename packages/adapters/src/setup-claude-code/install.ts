/** `<dataDir>/agents/claude-code`: the installed adapters and the temp folders an install works in. */
export const CLAUDE_CODE_DIR = join('agents', 'claude-code');

/** Prefix of the temp folders an install works in, inside {@link CLAUDE_CODE_DIR}. */
const WORK_PREFIX = '.install-';

/** How long npm may go without printing a line or growing its download before the install counts as stalled. */
export const NPM_IDLE_TIMEOUT_MS = 60_000;

/** An npm lockfile (v3), as far as the install reads it. */
export interface AdapterLock {
  lockfileVersion?: number;
  packages: Record<string, { version?: string; integrity?: string; optional?: boolean; link?: boolean; os?: string[]; cpu?: string[] }>;
}

/** The `package.json` and `package-lock.json` an install writes and runs `npm ci` on. */
export interface AdapterPins {
  packageJson: unknown;
  lock: AdapterLock;
}

/** The pinned adapter (`pins/`, generated by `scripts/agent-pins.mjs`). */
export const ADAPTER_PINS: AdapterPins = { packageJson: pinnedManifest, lock: pinnedLock as AdapterLock };

const ADAPTER_KEY = `node_modules/${CLAUDE_AGENT_ACP_PACKAGE}`;

/** The adapter version `pins` installs. */
export function pinnedVersion(pins: AdapterPins = ADAPTER_PINS): string {
  const version = pins.lock.packages[ADAPTER_KEY]?.version;
  if (version === undefined) throw new Error(`the adapter pins do not lock ${CLAUDE_AGENT_ACP_PACKAGE}`);
  return version;
}

/** The adapter's entry script inside an installed folder. */
const entryIn = (folder: string) => join(folder, 'node_modules', ...CLAUDE_AGENT_ACP_PACKAGE.split('/'), 'dist', 'index.js');

export interface InstalledAdapter {
  /** The entry script, `…/node_modules/@agentclientprotocol/claude-agent-acp/dist/index.js`. */
  path: string;
  version: string;
  /** Installed with the Agent SDK's own `claude`, so it needs no `claude` on this computer. */
  bundled: boolean;
}

/** `adapter-<version>[-bundled]`; a prerelease (`0.0.0-fixture`) may have no `-`, so `-bundled` is never taken for one. */
const INSTALLED_FOLDER = /^adapter-(\d+\.\d+\.\d+(?:-(?!bundled$)[0-9A-Za-z.]+)?)(-bundled)?$/;

/**
 * The adapter an install put in `<dataDir>/agents/claude-code/`, or
 * `undefined`. The pinned version comes first (bundled before not), then
 * the newest other version, so a release that bumps the pin keeps an
 * earlier install working.
 */
export function installedAdapter(dataDir: string, pins: AdapterPins = ADAPTER_PINS): InstalledAdapter | undefined {
  const dir = join(dataDir, CLAUDE_CODE_DIR);
  let names: string[];
  try {
    names = readdirSync(dir);
  } catch {
    return undefined;
  }
  const pinned = pinnedVersion(pins);
  const found = names
    .map((name) => ({ name, match: INSTALLED_FOLDER.exec(name) }))
    .filter((entry): entry is { name: string; match: RegExpExecArray } => entry.match !== null)
    .map(({ name, match }) => ({ path: entryIn(join(dir, name)), version: match[1]!, bundled: match[2] !== undefined }))
    .filter((adapter) => existsSync(adapter.path))
    .sort((a, b) => {
      if ((a.version === pinned) !== (b.version === pinned)) return a.version === pinned ? -1 : 1;
      if (a.version !== b.version) return b.version.localeCompare(a.version, 'en', { numeric: true });
      return Number(b.bundled) - Number(a.bundled);
    });
  return found[0];
}

/** npm's output lines and how it ended. */
export interface NpmProcess {
  /** Resolves once npm has exited (or failed to start: `exitCode` `null`, `startError` its errno code only, never a message or a path). */
  exited: Promise<{ exitCode: number | null; startError?: string }>;
  /** Stops npm. Safe to call more than once. */
  kill(): void;
}

export interface NpmRunInput {
  /** The Node that runs npm (`process.execPath`). */
  nodePath: string;
  npmCli: string;
  args: readonly string[];
  cwd: string;
  env: Record<string, string>;
  /** Each line npm prints, on either stream. Never logged. */
  onLine(line: string): void;
}

export type NpmRunner = (input: NpmRunInput) => NpmProcess;

/** An error's errno code (`ENOENT`), or `unknown`: never its message, which can hold paths. */
const errnoCode = (error: unknown): string => errorCode(error, 'unknown');

/** Runs `node npm-cli.js <args>`: an argument array, no shell, a hidden window on Windows. */
export const spawnNpm: NpmRunner = (input) => {
  let child: ReturnType<typeof spawn>;
  try {
    child = spawn(input.nodePath, [input.npmCli, ...input.args], {
      cwd: input.cwd,
      env: input.env,
      stdio: ['ignore', 'pipe', 'pipe'],
      shell: false,
      windowsHide: true,
    });
  } catch (error) {
    return { exited: Promise.resolve({ exitCode: null, startError: errnoCode(error) }), kill: () => {} };
  }
  const read = (stream: NodeJS.ReadableStream | null) => {
    if (stream === null) return;
    let buffer = '';
    stream.setEncoding('utf8');
    stream.on('data', (chunk: string) => {
      buffer += chunk;
      const lines = buffer.split(/\r?\n/);
      buffer = lines.pop() ?? '';
      for (const line of lines) input.onLine(line);
    });
    stream.on('end', () => {
      if (buffer !== '') input.onLine(buffer);
      buffer = '';
    });
    stream.on('error', () => {});
  };
  read(child.stdout);
  read(child.stderr);
  const exited = new Promise<{ exitCode: number | null; startError?: string }>((resolve) => {
    child.on('error', (error) => resolve({ exitCode: null, startError: errnoCode(error) }));
    child.on('close', (code) => resolve({ exitCode: code }));
  });
  return {
    exited,
    kill: () => {
      if (child.exitCode === null && child.signalCode === null) child.kill();
    },
  };
};

export interface InstallAdapterOptions {
  dataDir: string;
  /** Keep the optional dependencies, so the Agent SDK brings its own `claude` (no usable `claude` on this computer). */
  withBinary: boolean;
  onProgress: (progress: AgentInstallProgress) => void;
  /** Default {@link ADAPTER_PINS}; the tests pass a local fixture lock. */
  pins?: AdapterPins;
  /** Default {@link spawnNpm}. */
  runNpm?: NpmRunner;
  /** `npm_execpath` as the server found it at start (see {@link findNpmCli}). */
  launcherNpm?: string | undefined;
  /** Default {@link findNpmCli}, with {@link launcherNpm} and the `PATH` of {@link env}. */
  npmCli?: string;
  /** The Node that runs npm. Default `process.execPath`. */
  nodePath?: string;
  /** npm's environment, less every `npm_*` variable. Default `process.env`. */
  env?: Readonly<Record<string, string | undefined>>;
  /** Default {@link NPM_IDLE_TIMEOUT_MS}. */
  idleTimeoutMs?: number;
  /** Aborting stops npm; the install then rejects and leaves nothing. */
  signal?: AbortSignal;
  /** Told about temp files that could not be removed; they never change an install's outcome. */
  onCleanupError?: (error: unknown) => void;
}

const DOWNLOADING = `Downloading ${CLAUDE_CODE}`;
const CHECKING = `Checking ${CLAUDE_CODE}`;
const NO_NPM = `Ogden Agents couldn't find npm, so ${CLAUDE_CODE} wasn't installed. Install Node.js with npm, then try again.`;
const MISMATCH = "The download didn't match the expected files, so nothing was installed. Try again.";
const OFFLINE = "The download didn't finish. Check your internet connection and try again.";
const NO_SPACE = `${CLAUDE_CODE} couldn't be written to Ogden Agents' data folder. Check there is free space, then try again.`;
const FAILED = `${CLAUDE_CODE} couldn't be installed. Try again.`;
const NOT_RIGHT = `${CLAUDE_CODE} was downloaded but didn't look right, so nothing was installed. Try again.`;
const STOPPED = `Installing ${CLAUDE_CODE} was stopped.`;
const NO_BINARY = `${CLAUDE_CODE} has no build for this computer (${process.platform}-${process.arch}).`;

/** npm error codes that mean the network, not the package. */
const NETWORK_CODES = new Set(['ENOTFOUND', 'EAI_AGAIN', 'ECONNRESET', 'ECONNREFUSED', 'ETIMEDOUT', 'ESOCKETTIMEDOUT', 'ENETUNREACH', 'EHOSTUNREACH', 'ECONNABORTED', 'EPROTO', 'E500', 'E502', 'E503', 'E504']);

/** The plain words for npm's error code. */
function reasonFor(code: string | undefined): string {
  if (code === 'EINTEGRITY') return MISMATCH;
  if (code === 'ENOSPC' || code === 'EDQUOT') return NO_SPACE;
  if (code !== undefined && NETWORK_CODES.has(code)) return OFFLINE;
  return FAILED;
}

/**
 * npm's environment (AD-16): the base allowlist and what npm needs to reach
 * its registry as the user set it up (proxies, certificate authorities, its
 * config folders: `NPM_NETWORK`), never an agent key or any other variable
 * of this server's; no inherited `npm_*` settings (any case), plus npm's
 * cache in the temp folder.
 */
export function npmEnv(env: Readonly<Record<string, string | undefined>>, cache: string): Record<string, string> {
  const out = helperEnvironment(NPM_NETWORK, env);
  for (const name of Object.keys(out)) if (name.toLowerCase().startsWith('npm_')) delete out[name];
  out.npm_config_cache = cache;
  out.npm_config_update_notifier = 'false';
  return out;
}

/** Whether a lock entry's `os` and `cpu` (with `!` negations) allow this computer. */
function allowedHere(values: readonly string[] | undefined, current: string): boolean {
  if (values === undefined || values.length === 0) return true;
  if (values.includes(`!${current}`)) return false;
  const positive = values.filter((value) => !value.startsWith('!'));
  return positive.length === 0 || positive.includes(current);
}

/** How many packages `npm ci` fetches from `lock`: optional ones only when kept, and only for this OS and CPU. */
export function packagesToFetch(lock: AdapterLock, withBinary: boolean): number {
  return Object.entries(lock.packages).filter(([path, entry]) => {
    if (path === '' || entry.link === true) return false;
    if (entry.optional !== true) return true;
    return withBinary && allowedHere(entry.os, process.platform) && allowedHere(entry.cpu, process.arch);
  }).length;
}

/** A line npm prints for each package it has fetched with `--loglevel http`. */
const FETCHED = /^npm http (?:fetch GET 2\d\d |cache )/;
/** npm's error code line (`npm error code X`, or `npm ERR! code X` before npm 10). */
const ERROR_CODE = /^npm (?:error|ERR!) code ([A-Za-z0-9_]{1,40})\s*$/;

/** Total bytes of the files under `dir` (npm's download cache), best effort. */
function sizeOf(dir: string): number {
  let total = 0;
  let names: string[];
  try {
    names = readdirSync(dir, { recursive: true, encoding: 'utf8' });
  } catch {
    return 0;
  }
  for (const name of names) {
    try {
      const stat = statSync(join(dir, name));
      if (stat.isFile()) total += stat.size;
    } catch {
      // Moved or removed while walking.
    }
  }
  return total;
}

/** Removes temp folders a crashed or killed install left behind, best effort. */
function removeLeftovers(dir: string, onError: (error: unknown) => void): void {
  let entries: string[];
  try {
    entries = readdirSync(dir);
  } catch {
    return;
  }
  for (const entry of entries) {
    if (!entry.startsWith(WORK_PREFIX)) continue;
    restorePrevious(dir, join(dir, entry, 'previous'), onError);
    try {
      rmSync(join(dir, entry), { recursive: true, force: true, maxRetries: 3, retryDelay: 100 });
    } catch (error) {
      onError(error);
    }
  }
}

/**
 * A crash between moving an installed copy aside and renaming the new one
 * into place leaves the old copy in `<work>/previous/<name>` and nothing at
 * `<dir>/<name>`: it is moved back rather than deleted with the temp folder.
 */
function restorePrevious(dir: string, previous: string, onError: (error: unknown) => void): void {
  let names: string[];
  try {
    names = readdirSync(previous);
  } catch {
    return;
  }
  for (const name of names) {
    if (!INSTALLED_FOLDER.test(name) || existsSync(join(dir, name))) continue;
    try {
      renameSync(join(previous, name), join(dir, name));
    } catch (error) {
      onError(error);
    }
  }
}

/** Removes the `.install-*` folders a crashed or killed install left in `<dataDir>/agents/claude-code/` (server start). */
export function removeStaleInstalls(dataDir: string, onError: (error: unknown) => void = () => {}): void {
  removeLeftovers(join(dataDir, CLAUDE_CODE_DIR), onError);
}

/** The Claude Agent ACP adapter a chat or a sign-in runs, and what it needs. */
export interface LocatedAdapter {
  path: string;
  /** Its version, when it is the real adapter package. */
  version: string | null;
  /** Installed without the Agent SDK's own `claude`, so it runs only with the user's `claude`. */
  needsClaude: boolean;
}

/** The version in the `package.json` two folders up from `entry`, when that is the adapter package. */
function adapterVersionOf(entry: string): string | null {
  try {
    const manifest = JSON.parse(readFileSync(join(dirname(dirname(entry)), 'package.json'), 'utf8')) as { name?: unknown; version?: unknown };
    return manifest.name === CLAUDE_AGENT_ACP_PACKAGE && typeof manifest.version === 'string' ? manifest.version : null;
  } catch {
    return null;
  }
}

/**
 * Where the adapter is, read afresh at each call: `adapterPath` (a path, or
 * a function giving one: `$OGDEN_AGENTS_CLAUDE_ACP_PATH`, then a dev
 * install's `node_modules`) when it gives one, else what an install put in
 * `<dataDir>/agents/claude-code/`. `undefined` when there is none, or the
 * given path doesn't exist.
 */
export function locateClaudeAdapter(options: {
  adapterPath?: string | (() => string | undefined) | undefined;
  dataDir?: string | undefined;
  pins?: AdapterPins | undefined;
}): LocatedAdapter | undefined {
  const given = typeof options.adapterPath === 'function' ? options.adapterPath() : options.adapterPath;
  if (given !== undefined) return existsSync(given) ? { path: given, version: adapterVersionOf(given), needsClaude: false } : undefined;
  if (options.dataDir === undefined) return undefined;
  const installed = installedAdapter(options.dataDir, options.pins ?? ADAPTER_PINS);
  return installed === undefined ? undefined : { path: installed.path, version: installed.version, needsClaude: !installed.bundled };
}

/**
 * Installs the pinned adapter under `<dataDir>/agents/claude-code/`,
 * reporting progress. Resolves with what was installed, or rejects with an
 * {@link AgentSetupError} in plain words (its `details` carry the step and
 * npm's error code only) having left no temp folder and no half-installed copy.
 */
export async function installAdapter(options: InstallAdapterOptions): Promise<InstalledAdapter> {
  const pins = options.pins ?? ADAPTER_PINS;
  const version = pinnedVersion(pins);
  const onCleanupError = options.onCleanupError ?? (() => {});
  const npmCli =
    options.npmCli ?? findNpmCli({ execPath: options.nodePath ?? process.execPath, launcherNpm: options.launcherNpm, pathEnv: pathOf(options.env ?? process.env) });
  if (npmCli === undefined || !existsSync(npmCli)) throw new AgentSetupError(NO_NPM, { details: { step: 'find_npm' } });
  if (options.signal?.aborted === true) throw new AgentSetupError(STOPPED, { details: { step: 'start' } });

  const dir = join(options.dataDir, CLAUDE_CODE_DIR);
  let work: string;
  try {
    mkdirSync(dir, { recursive: true, mode: 0o700 });
    removeLeftovers(dir, onCleanupError);
    work = mkdtempSync(join(dir, WORK_PREFIX));
  } catch (error) {
    throw new AgentSetupError(NO_SPACE, { details: { step: 'prepare', code: errnoCode(error) }, cause: error });
  }
  try {
    const project = join(work, 'adapter');
    const cache = join(work, 'cache');
    mkdirSync(project);
    writeFileSync(join(project, 'package.json'), `${JSON.stringify(pins.packageJson, null, 2)}\n`);
    writeFileSync(join(project, 'package-lock.json'), `${JSON.stringify(pins.lock, null, 2)}\n`);

    await runCi({ ...options, npmCli, project, cache, total: packagesToFetch(pins.lock, options.withBinary) });

    options.onProgress({ step: CHECKING, percent: 95 });
    const entry = entryIn(project);
    let installed: string | undefined;
    try {
      installed = (JSON.parse(readFileSync(join(dirname(dirname(entry)), 'package.json'), 'utf8')) as { version?: string }).version;
    } catch {
      installed = undefined;
    }
    if (!existsSync(entry) || installed !== version) {
      throw new AgentSetupError(NOT_RIGHT, { details: { step: 'verify', installed: installed ?? null, pinned: version } });
    }
    if (options.withBinary && locksBinaries(pins.lock) && !hasBinary(project)) {
      throw new AgentSetupError(NO_BINARY, { details: { step: 'verify', platform: process.platform, arch: process.arch } });
    }

    const name = `adapter-${version}${options.withBinary ? '-bundled' : ''}`;
    const target = join(dir, name);
    // Aside under its own name, so a crash mid-swap can be undone at the next start (`restorePrevious`).
    mkdirSync(join(work, 'previous'));
    await moveIntoPlace(project, target, join(work, 'previous', name), onCleanupError);
    options.onProgress({ step: CHECKING, percent: 100 });
    return { path: entryIn(target), version, bundled: options.withBinary };
  } finally {
    try {
      rmSync(work, { recursive: true, force: true, maxRetries: 5, retryDelay: 100 });
    } catch (error) {
      onCleanupError(error);
    }
  }
}

/** Whether the lock has the Agent SDK's platform binaries (the real pins do; the test fixture doesn't). */
const locksBinaries = (lock: AdapterLock) =>
  Object.entries(lock.packages).some(([path, entry]) => entry.optional === true && path.startsWith('node_modules/@anthropic-ai/claude-agent-sdk-'));

/** Whether npm put a platform binary package of the Agent SDK in `project`. */
function hasBinary(project: string): boolean {
  try {
    return readdirSync(join(project, 'node_modules', '@anthropic-ai')).some((name) => name.startsWith('claude-agent-sdk-'));
  } catch {
    return false;
  }
}

/** `npm ci` in `project`, with progress, the idle timeout and the abort signal. Rejects in plain words. */
async function runCi(
  options: InstallAdapterOptions & { npmCli: string; project: string; cache: string; total: number },
): Promise<void> {
  const runNpm = options.runNpm ?? spawnNpm;
  const idleTimeoutMs = options.idleTimeoutMs ?? NPM_IDLE_TIMEOUT_MS;
  const args = [
    'ci',
    '--ignore-scripts',
    '--no-audit',
    '--no-fund',
    '--no-update-notifier',
    '--no-progress',
    '--color=false',
    '--loglevel',
    'http',
    ...(options.withBinary ? [] : ['--omit=optional']),
  ];
  let fetched = 0;
  let npmCode: string | undefined;
  let stalled = false;
  let aborted = false;
  const report = () => {
    const percent = options.total > 0 ? Math.min(90, Math.floor((fetched / options.total) * 90)) : null;
    options.onProgress({ step: DOWNLOADING, percent });
  };
  report();

  let idle: ReturnType<typeof setTimeout> | undefined;
  let lastSize = 0;
  let npm: NpmProcess | undefined;
  const armIdle = () => {
    clearTimeout(idle);
    idle = setTimeout(() => {
      // A large package downloads for a while before npm prints its line: a growing cache is progress too.
      const size = sizeOf(options.cache);
      if (size > lastSize) {
        lastSize = size;
        armIdle();
        return;
      }
      stalled = true;
      npm?.kill();
    }, idleTimeoutMs);
  };
  const onAbort = () => {
    aborted = true;
    npm?.kill();
  };

  armIdle();
  options.signal?.addEventListener('abort', onAbort, { once: true });
  try {
    npm = runNpm({
      nodePath: options.nodePath ?? process.execPath,
      npmCli: options.npmCli,
      args,
      cwd: options.project,
      env: npmEnv(options.env ?? process.env, options.cache),
      onLine: (line) => {
        armIdle();
        const code = ERROR_CODE.exec(line);
        if (code !== null) npmCode ??= code[1];
        if (FETCHED.test(line)) {
          fetched++;
          report();
        }
      },
    });
    if (options.signal?.aborted === true) onAbort();
    const { exitCode, startError } = await npm.exited;
    if (aborted) throw new AgentSetupError(STOPPED, { details: { step: 'npm_ci', stopped: true } });
    if (stalled) throw new AgentSetupError(OFFLINE, { details: { step: 'npm_ci', stalled: true, idleTimeoutMs } });
    if (startError !== undefined) throw new AgentSetupError(FAILED, { details: { step: 'npm_ci', startError: errnoCode({ code: startError }) } });
    if (exitCode !== 0) throw new AgentSetupError(reasonFor(npmCode), { details: { step: 'npm_ci', exitCode, npmCode: npmCode ?? null } });
  } finally {
    clearTimeout(idle);
    options.signal?.removeEventListener('abort', onAbort);
  }
}

/**
 * Renames `staging` to `target`. An existing copy is first moved aside (and
 * restored if the rename fails), so a failure never leaves no copy at all.
 */
async function moveIntoPlace(staging: string, target: string, aside: string, onCleanupError: (error: unknown) => void): Promise<void> {
  const hadPrevious = existsSync(target);
  // A folder Windows still holds (an antivirus scan of node_modules) gets longer than uv's to let go.
  if (hadPrevious) await renameWithRetry(target, aside, 10);
  try {
    await renameWithRetry(staging, target, 10);
  } catch (error) {
    if (hadPrevious) {
      try {
        await renameWithRetry(aside, target, 10);
      } catch (restoreError) {
        onCleanupError(restoreError);
      }
    }
    throw new AgentSetupError(`${CLAUDE_CODE} couldn't be put in place, so nothing changed. Try again.`, {
      details: { step: 'rename', code: errnoCode(error) },
      cause: error,
    });
  }
}
